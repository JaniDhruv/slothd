"""Tiger Data — PostgreSQL + pgvector integration for slothd.

Stores 768-dimensional file embeddings generated by nomic-embed-text
and provides cosine distance semantic similarity search via pgvector.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Any

logger = logging.getLogger(__name__)

CREATE_EXTENSION_SQL = "CREATE EXTENSION IF NOT EXISTS vector;"

CREATE_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS file_embeddings (
    id          SERIAL PRIMARY KEY,
    file_path   TEXT UNIQUE NOT NULL,
    file_name   TEXT NOT NULL,
    category    TEXT NOT NULL,
    subcategory TEXT,
    description TEXT,
    vendor      TEXT,
    file_date   TEXT,
    tags        TEXT[],
    embedding   vector(768),
    indexed_at  TIMESTAMPTZ DEFAULT NOW()
);
"""

CREATE_INDEX_SQL = """
CREATE INDEX IF NOT EXISTS file_embeddings_vec_idx
ON file_embeddings
USING hnsw (embedding vector_cosine_ops);
"""


@dataclass
class SearchResult:
    """A semantic search match from pgvector."""

    file_path: str
    file_name: str
    category: str
    subcategory: str | None
    description: str | None
    vendor: str | None
    file_date: str | None
    tags: list[str]
    similarity: float

    def to_dict(self) -> dict[str, Any]:
        return {
            "file_path": self.file_path,
            "file_name": self.file_name,
            "category": self.category,
            "subcategory": self.subcategory,
            "description": self.description,
            "vendor": self.vendor,
            "file_date": self.file_date,
            "tags": self.tags,
            "similarity": round(self.similarity, 4),
        }


class TigerDataClient:
    """Client for Tiger Data PostgreSQL instance with pgvector support."""

    def __init__(self, db_url: str) -> None:
        self.db_url = db_url
        self._connected = False

    def is_available(self) -> bool:
        """Check if Tiger Data / PostgreSQL is reachable and pgvector is enabled."""
        try:
            import psycopg

            with psycopg.connect(self.db_url, connect_timeout=3) as conn:
                with conn.cursor() as cur:
                    cur.execute("SELECT 1;")
                    return True
        except Exception as e:
            logger.debug("Tiger Data connection check failed: %s", e)
            return False

    def init_db(self) -> bool:
        """Initialize pgvector extension, table schema, and HNSW index.

        Returns:
            True if initialization succeeded, False otherwise.
        """
        try:
            import psycopg
            from pgvector.psycopg import register_vector

            with psycopg.connect(self.db_url) as conn:
                register_vector(conn)
                with conn.cursor() as cur:
                    cur.execute(CREATE_EXTENSION_SQL)
                    cur.execute(CREATE_TABLE_SQL)
                    try:
                        cur.execute(CREATE_INDEX_SQL)
                    except Exception as idx_err:
                        logger.debug("HNSW index creation skipped: %s", idx_err)
                conn.commit()
            logger.info("Tiger Data pgvector initialized successfully.")
            self._connected = True
            return True
        except Exception as e:
            logger.warning("Could not initialize Tiger Data pgvector: %s", e)
            self._connected = False
            return False

    def upsert_file_embedding(
        self,
        *,
        file_path: str,
        file_name: str,
        category: str,
        subcategory: str | None = None,
        description: str | None = None,
        vendor: str | None = None,
        file_date: str | None = None,
        tags: list[str] | None = None,
        embedding: list[float],
    ) -> bool:
        """Insert or update a file's embedding and metadata."""
        if len(embedding) != 768:
            logger.warning("Expected 768-dim embedding, got %d", len(embedding))

        tags_list = tags or []
        sql = """
        INSERT INTO file_embeddings (
            file_path, file_name, category, subcategory, description,
            vendor, file_date, tags, embedding, indexed_at
        ) VALUES (
            %s, %s, %s, %s, %s, %s, %s, %s, %s, NOW()
        )
        ON CONFLICT (file_path) DO UPDATE SET
            file_name = EXCLUDED.file_name,
            category = EXCLUDED.category,
            subcategory = EXCLUDED.subcategory,
            description = EXCLUDED.description,
            vendor = EXCLUDED.vendor,
            file_date = EXCLUDED.file_date,
            tags = EXCLUDED.tags,
            embedding = EXCLUDED.embedding,
            indexed_at = NOW();
        """
        try:
            import numpy as np
            import psycopg
            from pgvector.psycopg import register_vector

            with psycopg.connect(self.db_url) as conn:
                register_vector(conn)
                with conn.cursor() as cur:
                    vec = np.array(embedding, dtype=np.float32)
                    cur.execute(
                        sql,
                        (
                            file_path,
                            file_name,
                            category,
                            subcategory,
                            description,
                            vendor,
                            file_date,
                            tags_list,
                            vec,
                        ),
                    )
                conn.commit()
            return True
        except Exception as e:
            logger.error("Failed to upsert embedding in Tiger Data: %s", e)
            return False

    def search_similar(
        self,
        query_embedding: list[float],
        limit: int = 5,
        min_similarity: float = 0.3,
    ) -> list[SearchResult]:
        """Perform semantic cosine similarity search using pgvector.

        Cosine similarity = 1 - (embedding <=> query_embedding)
        """
        sql = """
        SELECT
            file_path,
            file_name,
            category,
            subcategory,
            description,
            vendor,
            file_date,
            tags,
            1 - (embedding <=> %s) AS similarity
        FROM file_embeddings
        WHERE embedding IS NOT NULL
        ORDER BY embedding <=> %s ASC
        LIMIT %s;
        """
        results: list[SearchResult] = []
        try:
            import numpy as np
            import psycopg
            from pgvector.psycopg import register_vector

            with psycopg.connect(self.db_url) as conn:
                register_vector(conn)
                with conn.cursor() as cur:
                    vec = np.array(query_embedding, dtype=np.float32)
                    cur.execute(sql, (vec, vec, limit))
                    rows = cur.fetchall()
                    for row in rows:
                        sim = float(row[8]) if row[8] is not None else 0.0
                        if sim >= min_similarity:
                            results.append(
                                SearchResult(
                                    file_path=row[0],
                                    file_name=row[1],
                                    category=row[2],
                                    subcategory=row[3],
                                    description=row[4],
                                    vendor=row[5],
                                    file_date=row[6],
                                    tags=list(row[7]) if row[7] else [],
                                    similarity=sim,
                                )
                            )
        except Exception as e:
            logger.error("Error during Tiger Data semantic search: %s", e)

        return results

    def count_indexed(self) -> int:
        """Count total indexed files."""
        try:
            import psycopg

            with psycopg.connect(self.db_url) as conn:
                with conn.cursor() as cur:
                    cur.execute("SELECT COUNT(*) FROM file_embeddings;")
                    row = cur.fetchone()
                    return row[0] if row else 0
        except Exception:
            return 0
